def _resource_lines() -> list[str]:
    lines = []
    for r in RESOURCES:
        extra = f" ({r['text']})" if "text" in r else ""
        lines.append(f"  {r['name']}: {r['phone']}{extra} - {r['for']}, {r['hours']}")
    return lines


def format_crisis_message(category: str = "general") -> str:
    """Resources with a short intro matched to the category. For a person
    on their own (v0.4 behaviour; individual sessions are v2). In a JOINT
    session, abuse must use format_joint_session_message() instead."""
    if category == "self_harm":
        intro = (
            "It sounds like things feel really heavy right now. You don't "
            "have to handle this alone. The people below are trained for "
            "exactly this and are free to contact:"
        )
    elif category == "harm_to_others":
        intro = (
            "It sounds like things have gotten really intense. If anyone is "
            "in immediate danger, please contact emergency services. The "
            "lines below can also help you think through what's happening:"
        )
    elif category == "abuse":
        intro = (
            "What you're describing matters and you deserve support. "
            "1800RESPECT specialises in this and is confidential:"
        )
    else:
        intro = "Some places that can help right now:"

    return "\n".join(
        [EMERGENCY_AU, "", intro, "", *_resource_lines(), "", INTERNATIONAL_FALLBACK]
    )


